  const state = { lang: "zh" };
  const listeners = new Set();

  function t(key, vars) {
    let s = (DICT[state.lang] && DICT[state.lang][key]) || (DICT.zh && DICT.zh[key]) || key;
    if (vars) for (const [k, v] of Object.entries(vars)) s = s.split(`{${k}}`).join(String(v));
    return s;
  }

  function L(zh, en) { return state.lang === "zh" ? zh : (en == null ? zh : en); }

  function setLang(lang) {
    state.lang = lang === "en" ? "en" : "zh";
    document.documentElement.setAttribute("data-lang", state.lang);
    document.documentElement.lang = state.lang === "zh" ? "zh-CN" : "en";
    apply();
    listeners.forEach(fn => { try { fn(state.lang); } catch (e) { console.error(e); } });
  }

  function apply(root) {
    const scope = root || document;
    scope.querySelectorAll("[data-i18n]").forEach(el => {
      const key = el.getAttribute("data-i18n");
      const val = t(key);
      if (val !== key) el.textContent = val;
    });
    scope.querySelectorAll("[data-i18n-html]").forEach(el => {
      const key = el.getAttribute("data-i18n-html");
      const val = t(key);
      if (val !== key) el.innerHTML = val;
    });
    scope.querySelectorAll("[data-i18n-title]").forEach(el => {
      el.title = t(el.getAttribute("data-i18n-title"));
    });
    scope.querySelectorAll("[data-i18n-aria]").forEach(el => {
      el.setAttribute("aria-label", t(el.getAttribute("data-i18n-aria")));
    });
    const input = document.getElementById("paletteInput");
    if (input) input.placeholder = t("nav.searchPlaceholder");
  }

  function onChange(fn) { listeners.add(fn); return () => listeners.delete(fn); }

  window.I18N = { DICT, t, L, setLang, apply, onChange, get lang() { return state.lang; }, get state() { return state; } };

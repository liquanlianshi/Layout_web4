import { chromium } from 'playwright';
const browser = await chromium.launch();
const page = await browser.newPage({ viewport: { width: 1440, height: 900 } });
const errs = [];
page.on('console', m => { if (m.type() === 'error') errs.push('CONSOLE: ' + m.text()); });
page.on('pageerror', e => errs.push('PAGEERROR: ' + e.message));
await page.goto('http://127.0.0.1:8080/', { waitUntil: 'networkidle' });
await page.waitForTimeout(1200);
await page.screenshot({ path: 'shots/_home.png', fullPage: false });
console.log('home title:', await page.title());
console.log('boot gone:', await page.locator('#boot').count());
console.log('chapters:', await page.locator('.chapter-card').count());
await page.goto('http://127.0.0.1:8080/#/read/1.1', { waitUntil: 'networkidle' });
await page.waitForTimeout(900);
await page.screenshot({ path: 'shots/_reader.png', fullPage: false });
console.log('reader h1:', await page.locator('.sec-head h1').textContent());
console.log('widgets:', await page.locator('.widget-mount svg').count());
await page.goto('http://127.0.0.1:8080/#/map', { waitUntil: 'networkidle' });
await page.waitForTimeout(700);
await page.screenshot({ path: 'shots/_map.png', fullPage: false });
console.log('map nodes:', await page.locator('.mapnode').count());
await page.goto('http://127.0.0.1:8080/#/lab', { waitUntil: 'networkidle' });
await page.waitForTimeout(900);
await page.screenshot({ path: 'shots/_lab.png', fullPage: false });
console.log('lab body:', await page.locator('.lab-subpanel').count());
console.log('ERRORS:\n' + errs.join('\n'));
await browser.close();
